import { Injectable, NotFoundException, UnauthorizedException, BadRequestException } from '@nestjs/common';
import { prisma, Dataset, User, DatasetVersion, DatasetFile } from '@dataforge/db';
import { CreateDatasetDto } from '@dataforge/shared';
import { calculateQualityScore } from '@dataforge/ai';

@Injectable()
export class DatasetsService {
  private slugify(text: string): string {
    return text
      .toString()
      .toLowerCase()
      .trim()
      .replace(/\s+/g, '-')
      .replace(/[^\w\-]+/g, '')
      .replace(/\-\-+/g, '-');
  }

  async getRequiredUser(walletAddress?: string): Promise<User> {
    if (!walletAddress) {
      throw new UnauthorizedException('Authentication wallet address is required');
    }
    const user = await prisma.user.findUnique({
      where: { walletAddress: walletAddress.toLowerCase() },
    });
    if (!user) {
      throw new UnauthorizedException('User not registered');
    }
    return user;
  }

  async create(createDto: CreateDatasetDto, walletAddress?: string): Promise<Dataset> {
    const user = await this.getRequiredUser(walletAddress);
    const slug = this.slugify(createDto.name);

    // Check if slug is unique for this owner
    const existing = await prisma.dataset.findUnique({
      where: {
        ownerId_slug: {
          ownerId: user.id,
          slug,
        },
      },
    });

    if (existing) {
      throw new BadRequestException(`A dataset repository named '${createDto.name}' (slug: ${slug}) already exists.`);
    }

    return prisma.dataset.create({
      data: {
        ownerId: user.id,
        name: createDto.name,
        slug,
        description: createDto.description,
        readme: createDto.readme || `# ${createDto.name}\n\nGenerated by DataForge AI.`,
        visibility: createDto.visibility || 'public',
        license: createDto.license || 'MIT',
        type: createDto.type,
        tags: createDto.tags || [],
      },
      include: {
        owner: true,
      },
    });
  }

  async findAllPublic(): Promise<any[]> {
    const datasets = await prisma.dataset.findMany({
      where: { visibility: 'public' },
      include: {
        owner: true,
        versions: {
          include: { files: true },
          orderBy: { createdAt: 'desc' },
        },
      },
      orderBy: { createdAt: 'desc' },
    });

    const datasetIds = datasets.map(d => d.id);
    const forks = await prisma.datasetFork.groupBy({
      by: ['sourceDatasetId'],
      where: { sourceDatasetId: { in: datasetIds } },
      _count: { id: true },
    });
    const forksMap = new Map(forks.map(f => [f.sourceDatasetId, f._count.id]));

    return datasets.map(d => {
      const forksCount = forksMap.get(d.id) || 0;
      const latestVersion = d.versions[0];
      const qualityScore = latestVersion
        ? calculateQualityScore(latestVersion.files.map(f => ({ path: f.path, size: Number(f.size) })), !!d.readme)
        : 0;

      return {
        ...d,
        forksCount,
        qualityScore,
      };
    });
  }

  async findByOwnerAndSlug(ownerNameOrWallet: string, slug: string): Promise<any> {
    // Owner could be username or wallet address
    const dataset = await prisma.dataset.findFirst({
      where: {
        slug,
        OR: [
          { owner: { username: ownerNameOrWallet } },
          { owner: { walletAddress: ownerNameOrWallet.toLowerCase() } },
        ],
      },
      include: {
        owner: true,
        versions: {
          include: { files: true },
          orderBy: { createdAt: 'desc' },
        },
      },
    });

    if (!dataset) {
      throw new NotFoundException(`Dataset not found: ${ownerNameOrWallet}/${slug}`);
    }

    const forksCount = await prisma.datasetFork.count({
      where: { sourceDatasetId: dataset.id },
    });

    const latestVersion = dataset.versions[0];
    const qualityScore = latestVersion
      ? calculateQualityScore(latestVersion.files.map(f => ({ path: f.path, size: Number(f.size) })), !!dataset.readme)
      : 0;

    return {
      ...dataset,
      forksCount,
      qualityScore,
      shelbyMode: process.env.SHELBY_MODE || 'mock',
    };
  }

  async update(id: string, updateData: Partial<Dataset>, walletAddress?: string): Promise<Dataset> {
    const user = await this.getRequiredUser(walletAddress);
    const dataset = await prisma.dataset.findUnique({ where: { id } });

    if (!dataset) {
      throw new NotFoundException('Dataset not found');
    }

    if (dataset.ownerId !== user.id) {
      throw new UnauthorizedException('You do not own this dataset');
    }

    return prisma.dataset.update({
      where: { id },
      data: {
        description: updateData.description,
        readme: updateData.readme,
        visibility: updateData.visibility,
        license: updateData.license,
        type: updateData.type,
        tags: updateData.tags,
      },
      include: { owner: true },
    });
  }

  async delete(id: string, walletAddress?: string): Promise<{ success: boolean }> {
    const user = await this.getRequiredUser(walletAddress);
    const dataset = await prisma.dataset.findUnique({ where: { id } });

    if (!dataset) {
      throw new NotFoundException('Dataset not found');
    }

    if (dataset.ownerId !== user.id) {
      throw new UnauthorizedException('You do not own this dataset');
    }

    // Cascade delete manually to clean up tables safely
    const versions = await prisma.datasetVersion.findMany({ where: { datasetId: id } });
    const versionIds = versions.map(v => v.id);

    await prisma.datasetFile.deleteMany({ where: { versionId: { in: versionIds } } });
    await prisma.datasetVersion.deleteMany({ where: { datasetId: id } });
    await prisma.dataset.delete({ where: { id } });

    return { success: true };
  }

  async fork(id: string, targetName?: string, walletAddress?: string): Promise<Dataset> {
    const user = await this.getRequiredUser(walletAddress);
    const sourceDataset = await prisma.dataset.findUnique({
      where: { id },
      include: {
        versions: {
          where: { status: 'ready' },
          orderBy: { createdAt: 'desc' },
          take: 1,
          include: { files: true },
        },
      },
    });

    if (!sourceDataset) {
      throw new NotFoundException('Source dataset not found');
    }

    const name = targetName || `${sourceDataset.name}-fork`;
    const slug = this.slugify(name);

    // Verify it doesn't already exist for target user
    const existing = await prisma.dataset.findUnique({
      where: {
        ownerId_slug: {
          ownerId: user.id,
          slug,
        },
      },
    });

    if (existing) {
      throw new BadRequestException(`You already have a dataset repository named '${name}' (slug: ${slug}).`);
    }

    // Create target dataset and associated records atomically in transaction
    return prisma.$transaction(async (tx) => {
      const targetDataset = await tx.dataset.create({
        data: {
          ownerId: user.id,
          name,
          slug,
          description: sourceDataset.description,
          readme: `# Forked from ${sourceDataset.name}\n\n${sourceDataset.readme || ''}`,
          visibility: 'public',
          license: sourceDataset.license,
          type: sourceDataset.type,
          tags: [...sourceDataset.tags, 'fork'],
        },
        include: { owner: true },
      });

      // If source has a ready version, clone the latest version
      const sourceVersion = sourceDataset.versions[0];
      if (sourceVersion) {
        // 1. Create target version
        const targetVersion = await tx.datasetVersion.create({
          data: {
            datasetId: targetDataset.id,
            version: sourceVersion.version,
            changelog: `Forked from ${sourceDataset.name} (v${sourceVersion.version})`,
            status: 'ready',
            totalSize: sourceVersion.totalSize,
            fileCount: sourceVersion.fileCount,
            manifestHash: sourceVersion.manifestHash,
            manifestShelbyBlobName: sourceVersion.manifestShelbyBlobName,
            manifestShelbyMerkleRoot: sourceVersion.manifestShelbyMerkleRoot,
          },
        });

        // 2. Clone all files
        if (sourceVersion.files && sourceVersion.files.length > 0) {
          await tx.datasetFile.createMany({
            data: sourceVersion.files.map((file) => ({
              versionId: targetVersion.id,
              path: file.path,
              mimeType: file.mimeType,
              size: file.size,
              sha256: file.sha256,
              shelbyBlobName: file.shelbyBlobName,
              shelbyAccount: file.shelbyAccount,
              shelbyMerkleRoot: file.shelbyMerkleRoot,
              explorerUrl: file.explorerUrl,
            })),
          });
        }

        // 3. Create DatasetFork lineage record
        await tx.datasetFork.create({
          data: {
            sourceDatasetId: sourceDataset.id,
            targetDatasetId: targetDataset.id,
            sourceVersionId: sourceVersion.id,
          },
        });

        // 4. Create DatasetLineage connection
        await tx.datasetLineage.create({
          data: {
            childVersionId: targetVersion.id,
            parentVersionId: sourceVersion.id,
            relationType: 'forked_from',
            note: `Forked dataset from repository ${sourceDataset.id}`,
          },
        });
      }

      return targetDataset;
    });
  }

  async getLineage(datasetId: string): Promise<any> {
    const dataset = await prisma.dataset.findUnique({
      where: { id: datasetId },
      include: { versions: true },
    });

    if (!dataset) {
      throw new NotFoundException('Dataset not found');
    }

    const versionIds = dataset.versions.map(v => v.id);

    // Find lineages where any version of this dataset is child or parent
    const lineages = await prisma.datasetLineage.findMany({
      where: {
        OR: [
          { childVersionId: { in: versionIds } },
          { parentVersionId: { in: versionIds } },
        ],
      },
      include: {
        // Fetch child and parent version metadata including the dataset details
        childVersion: {
          include: {
            dataset: {
              include: { owner: true }
            }
          }
        },
        parentVersion: {
          include: {
            dataset: {
              include: { owner: true }
            }
          }
        }
      }
    });

    // Format for React Flow:
    // Nodes: distinct dataset versions
    // Edges: connections between them
    const nodesMap = new Map<string, any>();
    const edges: any[] = [];

    // Add nodes for this dataset's versions in case there's no lineage record yet
    for (const v of dataset.versions) {
      const label = `${dataset.name} v${v.version}`;
      nodesMap.set(v.id, {
        id: v.id,
        label,
        datasetName: dataset.name,
        owner: '', // resolved later
        version: v.version,
        isCurrent: true,
      });
    }

    lineages.forEach((lin: any) => {
      const child = lin.childVersion;
      const parent = lin.parentVersion;

      if (child) {
        nodesMap.set(child.id, {
          id: child.id,
          label: `${child.dataset.name} v${child.version}`,
          datasetName: child.dataset.name,
          owner: child.dataset.owner?.username || child.dataset.owner?.walletAddress,
          version: child.version,
          isCurrent: child.datasetId === datasetId,
        });
      }

      if (parent) {
        nodesMap.set(parent.id, {
          id: parent.id,
          label: `${parent.dataset.name} v${parent.version}`,
          datasetName: parent.dataset.name,
          owner: parent.dataset.owner?.username || parent.dataset.owner?.walletAddress,
          version: parent.version,
          isCurrent: parent.datasetId === datasetId,
        });
      }

      edges.push({
        id: lin.id,
        source: lin.parentVersionId,
        target: lin.childVersionId,
        label: lin.relationType,
        animated: true,
      });
    });

    return {
      nodes: Array.from(nodesMap.values()),
      edges,
    };
  }

  async getTags(): Promise<string[]> {
    const datasets = await prisma.dataset.findMany({
      select: { tags: true },
    });
    const tagsSet = new Set<string>();
    datasets.forEach(d => {
      d.tags.forEach(t => tagsSet.add(t));
    });
    return Array.from(tagsSet);
  }

  async getTrending(): Promise<any[]> {
    const datasets = await prisma.dataset.findMany({
      where: { visibility: 'public' },
      include: {
        owner: true,
        versions: {
          include: { files: true },
          orderBy: { createdAt: 'desc' },
        },
      },
      orderBy: { createdAt: 'desc' },
      take: 6,
    });

    const datasetIds = datasets.map(d => d.id);
    const forks = await prisma.datasetFork.groupBy({
      by: ['sourceDatasetId'],
      where: { sourceDatasetId: { in: datasetIds } },
      _count: { id: true },
    });
    const forksMap = new Map(forks.map(f => [f.sourceDatasetId, f._count.id]));

    return datasets.map(d => {
      const forksCount = forksMap.get(d.id) || 0;
      const latestVersion = d.versions[0];
      const qualityScore = latestVersion
        ? calculateQualityScore(latestVersion.files.map(f => ({ path: f.path, size: Number(f.size) })), !!d.readme)
        : 0;

      return {
        ...d,
        forksCount,
        qualityScore,
      };
    });
  }
}
